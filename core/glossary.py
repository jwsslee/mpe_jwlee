def glossary_table(reference,query=''):
    rows=[]
    for term,meaning in sorted(MEANINGS.items()):
        examples=' · '.join(reference.loc[reference.group==term,'name'].head(3))
        rows.append({'비교군 용어':term,'쉬운 뜻':meaning,'기업 예시(기존 분류)':examples})
    frame=pd.DataFrame(rows)
    if query.strip():
        mask=frame.agg(' '.join,axis=1).str.contains(query.strip(),case=False,regex=False)
        frame=frame[mask]
    return frame
